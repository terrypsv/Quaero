// Seul le commentaire de tete compte. Un lien symbolique, meme dans un dossier
// du chemin, n'est pas suivi hors du depot.
func TestEnTeteGenere(t *testing.T) {
	root := t.TempDir()
	write := func(rel, body string) {
		full := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("internal/strings.go", "// Code generated by \"stringer -type=Kind\"; DO NOT EDIT.\r\n\npackage x\n")
	write("internal/licence.go", "// Copyright 2026 Exemple.\n// SPDX-License-Identifier: MIT\n\n// Code generated by tool. DO NOT EDIT.\n\npackage x\n")
	write("internal/plain.go", "package x\n\n// Code generated by tool. DO NOT EDIT.\n")
	write("web/bundle.js", "/**\n * @generated\n */\nvar a = 1;\n")
	write("web/late.js", "var a = 1;\n/* @generated */\n")
	write("proto/x_pb2.txt", "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n")
	write("internal/hand.go", "// Generated by hand, do not edit without review.\npackage x\n")

	for rel, want := range map[string]bool{
		"internal/strings.go": true,
		"internal/licence.go": true,
		"internal/plain.go":   false,
		"web/bundle.js":       true,
		"web/late.js":         false,
		"proto/x_pb2.txt":     true,
		"internal/hand.go":    false,
		"absent.go":           false,
		"../dehors.go":        false,
		"/etc/passwd":         false,
	} {
		if got := generatedHeader(root, rel); got != want {
			t.Errorf("%s: %v, attendu %v", rel, got, want)
		}
	}
	if runtime.GOOS != "windows" {
		outside := t.TempDir()
		_ = os.WriteFile(filepath.Join(outside, "secret.go"), []byte("// Code generated by x. DO NOT EDIT.\n"), 0o644)
		if err := os.Symlink(filepath.Join(outside, "secret.go"), filepath.Join(root, "lien.go")); err == nil && generatedHeader(root, "lien.go") {
			t.Error("lien symbolique suivi")
		}
		if err := os.Symlink(outside, filepath.Join(root, "dossier")); err == nil && generatedHeader(root, "dossier/secret.go") {
			t.Error("dossier lie hors du depot suivi")
		}
	}
}

// semgrep sans compte rend « requires login » a la place des lignes: Quaero
// les relit dans le depot.
func TestLignesSemgrepRelues(t *testing.T) {
	root := t.TempDir()
	_ = os.WriteFile(filepath.Join(root, "a.py"), []byte("import os\r\nos.system(cmd)\nprint(1)\n"), 0o644)
	raw := []byte(`{"results":[{"check_id":"python.x.y","path":"` + filepath.ToSlash(filepath.Join(root, "a.py")) + `","start":{"line":2},"end":{"line":2},"extra":{"message":"m","severity":"ERROR","lines":"requires login"}}]}`)
	fs, err := parseSemgrepAt(raw, root)
	if err != nil || len(fs) != 1 {
		t.Fatalf("%v %+v", err, fs)
	}
	var code string
	for _, e := range fs[0].Evidence {
		if e.Type == "code" {
			code = e.Data
		}
	}
	if code != "os.system(cmd)" {
		t.Errorf("lignes %q", code)
	}
	if got := repoLines(root, "a.py", 1, 400); got != "import os\nos.system(cmd)\nprint(1)" {
		t.Errorf("plage bornee au fichier: %q", got)
	}
	if got := repoLines(root, "../a.py", 1, 1); got != "" {
		t.Errorf("hors du depot: %q", got)
	}
}

// Le pre-tri etiquette sans rien retirer ni changer de gravite, et laisse les
// constats sur l'analyse elle-meme tranquilles.
func TestPretriSansRienRetirer(t *testing.T) {
	root := t.TempDir()
	in := []finding.Finding{
		codeAt("A", "internal/a.go:3", "gosec", finding.SeverityHigh, ""),
		codeAt("B", "internal/a_test.go:9", "semgrep", finding.SeverityHigh, ""),
		{ID: "QRO-SCAN-ABSENT-gosec", Severity: finding.SeverityInfo},
		vuln("QRO-OSV-X", finding.SeverityMedium, "osv-scanner", finding.Reference{Framework: "OSV", ID: "GO-1"}),
	}
	out := pretri(root, in)
	if len(out) != 4 || out[1].Severity != finding.SeverityHigh {
		t.Fatalf("constats changes: %+v", out)
	}
	if got := Contexts(out[0]); len(got) != 0 {
		t.Errorf("code du produit etiquete: %v", got)
	}
	if got := Contexts(out[1]); !reflect.DeepEqual(got, []string{ContextTest}) {
		t.Errorf("test: %v", got)
	}
	if got := Contexts(out[2]); len(got) != 0 {
		t.Errorf("constat d'analyse etiquete: %v", got)
	}
	if got := Contexts(out[3]); len(got) != 0 {
		t.Errorf("dependance etiquetee par le chemin: %v", got)
	}
}

// L'avis de govulncheck sur l'appel survit a la fusion avec osv-scanner, de
// part et d'autre.
func TestAppelSurvitALaFusion(t *testing.T) {
	ref := finding.Reference{Framework: "OSV", ID: "GO-2025-1"}
	gvc := vuln("QRO-VULN-GO-2025-1", finding.SeverityMedium, "govulncheck", ref)
	gvc.Evidence = append(gvc.Evidence, finding.Evidence{Type: EvidenceContext, Data: ContextNotCalled})
	osv := vuln("QRO-OSV-GO-2025-1", finding.SeverityHigh, "osv-scanner", ref)
	for _, order := range [][]finding.Finding{{gvc, osv}, {osv, gvc}} {
		kept := dedupe(order)
		if len(kept) != 1 || !hasContext(kept[0], ContextNotCalled) {
			t.Errorf("etiquette perdue: %+v", kept)
		}
	}
}

func TestGovulncheckDitLAppel(t *testing.T) {
	raw := []byte(`{"osv":{"id":"GO-1","summary":"s"}}
{"finding":{"osv":"GO-1","trace":[{"module":"golang.org/x/net","version":"v0.1.0","package":"golang.org/x/net/html","function":"Parse","position":{"filename":"main.go","line":4}}]}}
{"osv":{"id":"GO-2","summary":"t"}}
{"finding":{"osv":"GO-2","trace":[{"module":"golang.org/x/text","version":"v0.1.0"}]}}`)
	fs, err := parseGovulncheck(raw)
	if err != nil || len(fs) != 2 {
		t.Fatalf("%v %+v", err, fs)
	}
	if !hasContext(fs[0], ContextCalled) || !hasContext(fs[1], ContextNotCalled) {
		t.Errorf("appel: %v, %v", Contexts(fs[0]), Contexts(fs[1]))
	}
}

// Bout a bout: RunWith pose les etiquettes sur ce que rendent les moteurs.
func TestRunPoseLesEtiquettes(t *testing.T) {
	root := t.TempDir()
	_ = os.MkdirAll(filepath.Join(root, "gen"), 0o755)
	_ = os.WriteFile(filepath.Join(root, "gen", "z.go"), []byte("// Code generated by tool. DO NOT EDIT.\npackage gen\n"), 0o644)
	s := fakeScanner{name: "gosec", available: true, findings: []finding.Finding{
		codeAt("QRO-GOSEC-1", "gen/z.go:2", "", finding.SeverityMedium, ""),
		codeAt("QRO-GOSEC-2", "main.go:7", "", finding.SeverityMedium, ""),
	}}
	rep, err := RunWith(context.Background(), root, "test", Options{}, s)
	if err != nil {
		t.Fatal(err)
	}
	tags := map[string][]string{}
	for _, f := range rep.Findings {
		tags[f.ID] = Contexts(f)
	}
	if !reflect.DeepEqual(tags["QRO-GOSEC-1"], []string{ContextGenerated}) || len(tags["QRO-GOSEC-2"]) != 0 {
		t.Errorf("etiquettes: %v", tags)
	}
}
