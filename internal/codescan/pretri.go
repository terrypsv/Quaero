// Le pre-tri pose sur chaque constat des etiquettes de contexte, tirees de
// regles simples et verifiables: ou se trouve le fichier, s'il est genere, si
// govulncheck a trouve un appel au code fautif. Il ne retire aucun constat et
// ne change aucune gravite. Il dit seulement ou regarder d'abord: une faille
// dans un test ou un exemple touche rarement ceux qui utilisent le logiciel.
//
// Aucun modele de langage n'intervient, et rien ne quitte la machine.

// EvidenceContext est le type de preuve qui porte une etiquette de pre-tri.
const EvidenceContext = "contexte"

// Etiquettes de pre-tri.
const (
	// ContextTest: code de test, jeux d'essai, maquettes.
	ContextTest = "test"
	// ContextExample: exemple, demonstration, documentation.
	ContextExample = "exemple"
	// ContextGenerated: code genere, ou recopie d'un tiers (vendor,
	// node_modules), que le depot ne corrige pas lui-meme.
	ContextGenerated = "genere"
	// ContextCI: chaine d'integration continue. Gardee dans la liste: une
	// faille de CI se signale comme une autre.
	ContextCI = "ci"
	// ContextCalled et ContextNotCalled: govulncheck a trouve, ou non, un
	// appel au symbole vulnerable d'une dependance.
	ContextCalled    = "appele"
	ContextNotCalled = "non_appele"
)

// OffProduct dit si une etiquette range le constat a part de la liste: un
// test, un exemple, ou du code tiers ou genere, que le depot ne corrige pas
// lui-meme.
func OffProduct(tag string) bool {
	return tag == ContextTest || tag == ContextExample || tag == ContextGenerated
}

// headBytes borne la lecture de l'en-tete d'un fichier pour y chercher la
// marque d'un code genere.
const headBytes = 4096

// Les regles restent etroites: une etiquette de trop range un vrai constat a
// part. Un dossier « doc », « sample » ou « mock » peut etre du code livre, un
// fichier « _gen.go » un generateur de cles: ils restent dans la liste.
var (
	testDirs = set("test", "tests", "__tests__", "testdata", "e2e", "fixtures", "fixture",
		"__mocks__", "mocks", "testutil", "testutils")
	exampleDirs   = set("example", "examples", "_examples", "demo", "demos", "tutorial", "tutorials")
	generatedDirs = set("vendor", "node_modules", "third_party", "third-party", "thirdparty",
		"generated", "__generated__", "bower_components")
	// rootTestDirs et rootGeneratedDirs ne comptent qu'a la racine du depot:
	// pkg/spec ou cmd/dist peuvent etre du code du produit.
	rootTestDirs      = set("spec", "specs")
	rootGeneratedDirs = set("dist")
	ciDirs            = set(".circleci", ".buildkite", ".woodpecker")
	ciFiles           = set(".gitlab-ci.yml", ".travis.yml", "jenkinsfile", "azure-pipelines.yml",
		".drone.yml", "bitbucket-pipelines.yml", "appveyor.yml", ".appveyor.yml", "cloudbuild.yaml")

	// testFileRe suit les conventions de nommage des tests par langage. Le nom
	// garde sa casse: FooTest.java est un test, Contest.java non.
	testFileRe = regexp.MustCompile(`(_test\.go|^test_.*\.py|_test\.py|^conftest\.py|\.(test|spec)\.[cm]?[jt]sx?|[a-z0-9](Test|Tests)\.(java|kt|cs|php|scala|groovy)|_(spec|test)\.rb)$`)
	genFileRe  = regexp.MustCompile(`(?i)(\.pb\.go|\.pb\.gw\.go|_pb2(_grpc)?\.py|\.min\.(js|css)|^zz_generated.*\.go|\.generated\.\w+|^bindata\.go)$`)
	// Marques d'un fichier genere, cherchees dans le seul commentaire de tete,
	// avant la premiere ligne de code: la convention Go (« Code generated ...
	// DO NOT EDIT. »), @generated, et « Generated by ... DO NOT EDIT ».
	goGenRe    = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)
	otherGenRe = regexp.MustCompile(`@generated\b|(?i:generated by).{0,80}DO NOT EDIT`)
	// lineSuffix est le numero de ligne, ou la plage de lignes (gosec), qui
	// suit le fichier dans la cible d'un constat de code.
	lineSuffix = regexp.MustCompile(`:\d+(-\d+)?$`)
)

func set(items ...string) map[string]bool {
	m := make(map[string]bool, len(items))
	for _, s := range items {
		m[s] = true
	}
	return m
}

// pretri pose les etiquettes de contexte sur les constats de code. root est le
// dossier analyse: l'en-tete des fichiers y est lu pour reconnaitre le code
// genere. Les dependances recoivent les leurs de govulncheck (projectVuln).
func pretri(root string, fs []finding.Finding) []finding.Finding {
	for i := range fs {
		f := &fs[i]
		if published(*f) || isMeta(*f) {
			continue
		}
		p := codePath(*f)
		if p == "" {
			continue
		}
		for _, tag := range pathTags(p) {
			addContext(f, tag)
		}
		if !hasContext(*f, ContextGenerated) && generatedHeader(root, p) {
			addContext(f, ContextGenerated)
		}
	}
	return fs
}

// pathTags rend les etiquettes qu'un chemin du depot justifie a lui seul.
func pathTags(p string) []string {
	p = filepath.ToSlash(p)
	segs := strings.Split(strings.ToLower(p), "/")
	base := segs[len(segs)-1]
	dirs := segs[:len(segs)-1]
	orig := p[strings.LastIndex(p, "/")+1:]

	var tags []string
	add := func(tag string) {
		for _, t := range tags {
			if t == tag {
				return
			}
		}
		tags = append(tags, tag)
	}
	for i, d := range dirs {
		switch {
		case testDirs[d], i == 0 && rootTestDirs[d]:
			add(ContextTest)
		case exampleDirs[d]:
			add(ContextExample)
		case generatedDirs[d], i == 0 && rootGeneratedDirs[d]:
			add(ContextGenerated)
		case ciDirs[d]:
			add(ContextCI)
		case d == ".github" && i+1 < len(dirs) && (dirs[i+1] == "workflows" || dirs[i+1] == "actions"):
			add(ContextCI)
		}
	}
	if testFileRe.MatchString(orig) {
		add(ContextTest)
	}
	if genFileRe.MatchString(base) {
		add(ContextGenerated)
	}
	if ciFiles[base] {
		add(ContextCI)
	}
	return tags
}

// generatedHeader cherche la marque d'un code genere dans le commentaire de
// tete d'un fichier du depot, comme go/ast.IsGenerated pour Go: une marque
// ecrite plus bas, dans le code, ne compte pas.
func generatedHeader(root, rel string) bool {
	head, ok := readRepoHead(root, rel, headBytes)
	if !ok {
		return false
	}
	text := strings.TrimPrefix(strings.ReplaceAll(string(head), "\r\n", "\n"), "\ufeff")
	inBlock := ""
	for _, line := range strings.Split(text, "\n") {
		t := strings.TrimSpace(line)
		switch {
		case inBlock != "":
			if strings.Contains(t, inBlock) {
				inBlock = ""
			}
		case t == "":
			continue
		case strings.HasPrefix(t, "/*"):
			if !strings.Contains(t[2:], "*/") {
				inBlock = "*/"
			}
		case strings.HasPrefix(t, "<!--"):
			if !strings.Contains(t[4:], "-->") {
				inBlock = "-->"
			}
		case strings.HasPrefix(t, "//"), strings.HasPrefix(t, "#"), strings.HasPrefix(t, "--"):
		default:
			// Premiere ligne de code: le commentaire de tete est fini.
			return false
		}
		if goGenRe.MatchString(strings.TrimRight(line, " \t")) || otherGenRe.MatchString(line) {
			return true
		}
	}
	return false
}

// codePath rend le fichier d'un constat de code, sans le numero de ligne.
func codePath(f finding.Finding) string {
	if f.Target == nil || f.Target.Type != "code" {
		return ""
	}
	id := lineSuffix.ReplaceAllString(f.Target.Identifier, "")
	return path.Clean(filepath.ToSlash(id))
}

// published reconnait une vulnerabilite publiee d'une dependance.
func published(f finding.Finding) bool {
	if f.Target != nil && f.Target.Type == "dependency" {
		return true
	}
	return len(publicIDs(f)) > 0
}

// isMeta reconnait un constat sur l'analyse elle-meme (moteur absent, en
// echec, rien a analyser).
func isMeta(f finding.Finding) bool {
	return strings.HasPrefix(f.ID, "QRO-SCAN-")
}

func addContext(f *finding.Finding, tag string) {
	if !hasContext(*f, tag) {
		f.Evidence = append(f.Evidence, finding.Evidence{Type: EvidenceContext, Data: tag})
	}
}

func hasContext(f finding.Finding, tag string) bool {
	for _, e := range f.Evidence {
		if e.Type == EvidenceContext && e.Data == tag {
			return true
		}
	}
	return false
}

// Contexts rend les etiquettes de pre-tri d'un constat.
func Contexts(f finding.Finding) []string {
	var out []string
	for _, e := range f.Evidence {
		if e.Type == EvidenceContext {
			out = append(out, e.Data)
		}
	}
	return out
}
